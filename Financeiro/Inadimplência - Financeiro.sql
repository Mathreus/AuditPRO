  TIPO_DOC_LC_COMPENSACAO,
  FORMA_PAGAMENTO,
  MES,
  UF_CLIENTE,
  CENTRO_PRIORIDADE,

  CONCAT(
    IF(COALESCE(VALOR_INADIMPLENCIA, 0) < 0, '-', ''),
    REGEXP_REPLACE(
      REVERSE(
        REGEXP_REPLACE(
          REVERSE(
            SPLIT(
              FORMAT('%.2f', ABS(COALESCE(VALOR_INADIMPLENCIA, 0))),
              '.'
            )[OFFSET(0)]
          ),
          r'(\d{3})',
          r'\1.'
        )
      ),
      r'^\.',
      ''
    ),
    ',',
    SPLIT(
      FORMAT('%.2f', ABS(COALESCE(VALOR_INADIMPLENCIA, 0))),
      '.'
    )[OFFSET(1)]
  ) AS VALOR_INADIMPLENCIA

