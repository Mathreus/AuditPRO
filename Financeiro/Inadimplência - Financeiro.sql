WITH parametros AS (
  SELECT
    data_base,
    30 AS atraso_minimo,
    DATE '2010-01-01' AS dt_inicio,
    ['H','E','I'] AS formas_pagamento
  FROM UNNEST(
    GENERATE_DATE_ARRAY(
      DATE '2024-01-01',
      DATE '2026-05-01',
      INTERVAL 1 MONTH
    )
  ) AS data_base
),

-- =====================================================================
--    ------------------        BASES        ------------------
-- =====================================================================

base_bseg AS (
  SELECT
    TRIM(BELNR) AS BELNR,
    TRIM(AUGBL) AS AUGBL,
    TRIM(VBELN) AS VBELN,
    TRIM(KUNNR) AS KUNNR,
    TRIM(BUZEI) AS BUZEI,
    SAFE_CAST(NETDT AS DATE) AS NETDT,
    SAFE_CAST(AUGDT AS DATE) AS AUGDT,
    SAFE_CAST(H_BUDAT AS DATE) AS H_BUDAT,
    EXTRACT(MONTH FROM SAFE_CAST(H_BUDAT AS DATE)) AS H_BUDAT_M,
    TRIM(H_BLART) AS H_BLART,
    TRIM(ZLSCH) AS ZLSCH,
    SAFE_CAST(DMBTR AS NUMERIC) AS DMBTR,
    TRIM(KOART) AS KOART,
    TRIM(SHKZG) AS SHKZG,
    TRIM(PSWSL) AS PSWSL
  FROM
    prdmgm_sap_cdc_processed.bseg
),

base_kna1 AS (
  SELECT DISTINCT
    TRIM(KUNNR) AS KUNNR,
    TRIM(LAND1) AS LAND1,
    TRIM(REGIO) AS UF_CLIENTE,
    CASE TRIM(KATR6)
      WHEN '01' THEN 'Consumo'
      WHEN '02' THEN 'Revenda'
      ELSE 'Não classificado'
    END AS FINALIDADE_COMPRA
  FROM
    prdmgm_sap_cdc_processed.kna1
),

/*
base_zsdt AS (
