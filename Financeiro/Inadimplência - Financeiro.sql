  WHERE
    TRIM(PRIORIDADE) = '0'
    AND TRIM(ATIVO) = 'X'
    AND NULLIF(TRIM(CENTRO), '') IS NOT NULL
),
*/

base_compensacao AS (
  SELECT
    BELNR AS LC_COMPENSACAO,
    ANY_VALUE(H_BLART) AS TIPO_DOC_LC_COMPENSACAO
  FROM
    base_bseg
  WHERE
    NULLIF(BELNR, '') IS NOT NULL
  GROUP BY
    BELNR
),

itens_base AS (
  SELECT
    b.BELNR,
    b.AUGBL,
    b.VBELN,
    b.KUNNR,
    b.BUZEI,
    b.NETDT,
    b.AUGDT,
    b.H_BUDAT,
    b.H_BUDAT_M,
    b.H_BLART,
    b.ZLSCH,
    b.DMBTR,
    b.KOART,
    b.SHKZG,
    b.PSWSL,

    k.LAND1,
    k.UF_CLIENTE,
    k.FINALIDADE_COMPRA,

    -- Como a base_zsdt está comentada, mantive o campo como nulo
    -- para não gerar erro no SELECT final.
    CAST(NULL AS STRING) AS CENTRO_PRIORIDADE,

    c.TIPO_DOC_LC_COMPENSACAO,

    p.data_base,
    p.atraso_minimo,
    p.dt_inicio,
    p.formas_pagamento

  FROM
    base_bseg b

  LEFT JOIN
    base_kna1 k
    ON k.KUNNR = b.KUNNR

  /*
  LEFT JOIN
    base_zsdt z
    ON z.KUNNR = b.KUNNR
  */

  LEFT JOIN
    base_compensacao c
    ON c.LC_COMPENSACAO = b.AUGBL

  CROSS JOIN
    parametros p

  WHERE
    b.KOART = 'D'
    AND SAFE_CAST(b.KUNNR AS INT64) > 1000000000
    AND k.LAND1 = 'BR'
    AND b.SHKZG = 'S'
    AND b.PSWSL = 'BRL'
    AND COALESCE(b.ZLSCH, '') IN UNNEST(p.formas_pagamento)
),

